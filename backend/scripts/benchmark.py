"""Run the held-out evaluation and write docs/EVALUATION_RESULTS.md from the stored run.

Usage (from backend/): .venv/bin/python scripts/benchmark.py [--quick]
The report is generated only from the benchmark run record; nothing is typed in by hand.
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.config import DATABASE, REPO_DIR  # noqa: E402
from app.models.run import RunRecord  # noqa: E402
from app.services.benchmark import run_benchmark  # noqa: E402
from app.services.evaluation import VARIANTS  # noqa: E402
from app.services.fleet import ensure_passports  # noqa: E402
from app.services.jobs import SimulationWorker, create_run, run_guarded  # noqa: E402
from app.services.registry import Registry  # noqa: E402

FAMILIES = ["wall_reach_v1", "wall_roof_v1"]
REPORT = REPO_DIR / "docs" / "EVALUATION_RESULTS.md"


def _fmt(v, kind: str = "") -> str:
    if v is None:
        return "—"
    if kind == "rate":
        return f"{v:.0%}"
    if kind == "mm":
        return f"{v * 1000:.2f}"
    if kind == "s":
        return f"{v:.3f}"
    return f"{v:g}" if isinstance(v, float) else str(v)


def render_report(run: RunRecord) -> str:
    res, proto = run.results, run.results["protocol"]
    lines = [
        "# Evaluation results (generated)",
        "",
        f"Generated by `backend/scripts/benchmark.py` from benchmark run `{run.run_id}` "
        f"({run.created_at:%Y-%m-%d %H:%M UTC}, {run.simulator}). Do not edit by hand.",
        "",
        f"- Source robot (dev library): `{proto['source_robot_id']}` · target robot (evaluated): `{proto['target_robot_id']}`",
        f"- Families: {', '.join(proto['families'])}; dev seeds {proto['dev_seeds'][0]}–{proto['dev_seeds'][-1]}, "
        f"held-out seeds {proto['eval_seeds'][0]}–{proto['eval_seeds'][-1]}",
        f"- Physics budget per scene: {proto['physics_budget_per_scene']}; {proto['kinematic_budget_per_scene']}",
        f"- Retrieval: {proto['retrieval']}",
        f"- Accounting: {proto['accounting']}",
        f"- Leakage: {proto['leakage']}",
        f"- Success: {proto['success']}",
        f"- {proto['meta']}",
        "",
        "## Dev library (source robot)",
        "",
        f"{sum(d['success'] for d in res['dev_library'])}/{len(res['dev_library'])} dev scenes produced a verified capsule.",
        "",
        "| Dev scene | Verified | Strategy |", "|---|---|---|",
        *[f"| {d['scene_id']} | {'yes' if d['success'] else 'no'} | {d['strategy'] or '—'} |" for d in res["dev_library"]],
        "",
        "## Summary",
        "",
        "Success rate uses applicable scenes as the denominator (a transfer variant is not applicable when no dev "
        "capsule exists for the family or the target cannot reach the start). **common** = scenes where every "
        "variant was applicable — the like-for-like comparison.",
        "",
    ]
    subsets = list(res["summary"][VARIANTS[0]].keys())
    for subset in subsets:
        lines += [f"### {subset}", "",
                  "| Variant | Success | Med. kinematic evals | Med. rollouts to 1st success | Med. error (mm) | "
                  "Med. wall time (s) | Sim steps | Collisions in rollouts | API calls |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for v in VARIANTS:
            s = res["summary"][v][subset]
            lines.append(
                f"| {v} | {s['successes']}/{s['applicable']} ({_fmt(s['success_rate'], 'rate')}) | "
                f"{_fmt(s['median_kinematic_evaluations'])} | {_fmt(s['median_rollouts_to_first_success'])} | "
                f"{_fmt(s['median_endpoint_error_m'], 'mm')} | {_fmt(s['median_wall_time_s'], 's')} | "
                f"{s['total_sim_steps']} | {s['collisions_in_rollouts']} | {s['api_calls']} |")
        lines.append("")
    lines += ["## Paired per-scene comparison vs baseline_no_sharing", "",
              "Scenes where both were applicable. Kinematic-evaluation comparison only over scenes both solved.", "",
              "| Variant | Scenes | Both ✓ | Only variant ✓ | Only baseline ✓ | Neither | Fewer evals | Same | More evals |",
              "|---|---|---|---|---|---|---|---|---|"]
    for v, pr in res.get("paired", {}).items():
        lines.append(f"| {v} | {pr['scenes']} | {pr['both_succeeded']} | {pr['only_variant']} | {pr['only_baseline']} | "
                     f"{pr['neither']} | {pr['fewer_kinematic_evals']} | {pr['same_kinematic_evals']} | {pr['more_kinematic_evals']} |")
    lines += ["", "## Raw rows", "",
              "| Scene | Variant | Applicable | Success | Selected | Kin. evals | Rollouts | Error (mm) | Source strategy | Note |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for r in res["rows"]:
        lines.append(f"| {r['scene_id']} | {r['variant']} | {'yes' if r['applicable'] else 'no'} | "
                     f"{'✓' if r['success'] else '✕'} | {r['selected'] or '—'} | {r['kinematic_evaluations']} | "
                     f"{r['physics_rollouts']} | {_fmt(r['endpoint_error_m'], 'mm')} | {r['source_strategy'] or '—'} | "
                     f"{r['note'] or ''} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="3 dev + 3 eval seeds per family (smoke)")
    ap.add_argument("--no-report", action="store_true")
    args = ap.parse_args()
    logging.basicConfig(level=logging.WARNING)
    dev, ev = (list(range(3)), list(range(100, 103))) if args.quick else (list(range(10)), list(range(100, 110)))
    registry, worker = Registry(DATABASE), SimulationWorker()
    try:
        worker.submit(ensure_passports, worker, registry).result()
        run = create_run(registry, "benchmark", ev[0], "evaluation_v1", source_robot_id="panda_01",
                         target_robot_id="ur5e_01")
        final = worker.submit(run_guarded, registry, run.run_id, lambda ctx: run_benchmark(
            ctx, registry, FAMILIES, dev, ev, "panda_01", "ur5e_01")).result()
    finally:
        worker.shutdown()
    print(f"{final.run_id}: {final.status} in {final.wall_clock_seconds:.1f}s")
    if final.status != "succeeded":
        print(final.error or final.events[-1].message)
        return 1
    for v in VARIANTS:
        s = final.results["summary"][v]
        print(f"  {v:20s} all {s['all']['successes']}/{s['all']['applicable']}  common {s['common']['successes']}/{s['common']['applicable']}"
              f"  med kin evals {s['common']['median_kinematic_evaluations']}  med rollouts {s['common']['median_rollouts_to_first_success']}")
    if not args.no_report:
        REPORT.write_text(render_report(final))
        print("wrote", REPORT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
